		function MergeGridCells(TableID,rCols) {
		  var dimension_cells = new Array();
		  var dimension_col = null;
		  for(Col in rCols) {
			dimension_col=rCols[Col];
			// first_instance holds the first instance of identical td
			var first_Hash="";
			var first_instance = null;
			var rowspan = 1;
			// iterate through rows
			$("#"+TableID+"> tbody > tr").children("td").attr('hidden', false);
			$("#"+TableID+"> tbody > tr").children("td").attr('rowspan', 1);
			$("#"+TableID).find('tr').each(function () {
			  // find the td of the correct column (determined by the dimension_col set above)
			  var dimension_td = $(this).find('td:nth-child(' + dimension_col + ')');
			  var dim_Hash="";
			  for(x=1;x<dimension_col;x++){
				dim_Hash+=$(this).find('td:nth-child(' + x + ')').text();
			  }
			  if (first_instance === null) {
				  // must be the first row
				  first_instance = dimension_td;
			  } else if (dimension_td.text() === first_instance.text() && first_Hash === dim_Hash) {
				  // the current td is identical to the previous AND the Hashes are as well
				  // remove the current td
				  // dimension_td.remove();
				  dimension_td.attr('hidden', true);
				  ++rowspan;
				  // increment the rowspan attribute of the first instance
				  first_instance.attr('rowspan', rowspan);
			  } else {
				  // this cell is different from the last
				  first_instance = dimension_td;
				  first_Hash = dim_Hash;
				  rowspan = 1;
			  }
			});
		  }
		}
		//FOOTER TABLES
		function SubDataTable(Table){
			var names = [];
			var nations = [];
			Table.data.forEach((row) => {
				names.push(row[1]);
				nations.push(row[2]);
			});
			var player_count = names.reduce((cnt, cur) => (cnt[cur] = cnt[cur] + 1 || 1, cnt), {});
			var player_array = Object.entries(player_count);
			player_array.forEach((col) => {
				let index = player_array.indexOf(col);
				for(var row of Table.data){
					if (col[0] == row[1]){
						player_array[index].splice(1,0,row[2]);
						break;
					}
				};
			});
			player_array = player_array.sort((a, b) => b[2] - a[2]);
			
			var nation_count = nations.reduce((cnt, cur) => (cnt[cur] = cnt[cur] + 1 || 1, cnt), {});
			var nation_array = Object.entries(nation_count);
			for (var col of nation_array){
				let index = nation_array.indexOf(col);
				if(col[0] == ""){
					nation_array.splice(index,1);
					break;
				}
			};
			nation_array = nation_array.sort((a, b) => b[2] - a[2]);
			
			//Multiple Record Holders Table
			$('#multiple-records').DataTable({
				'paging':false,
				'searching':false,
				'lengthChange':false,
				'info':false,
				'order':[],
				columns: [
					{ title: 'Player' },
					{ title: 'Nation' },
					{ title: "WR's" },
				],
				data: player_array,
				'columnDefs':[
					{'target':"_all",'searchable':false,'orderable':false,'className':'text-center align-middle'},
				]
			});
			//Nation Record Holders Table
			$('#nation-records').DataTable({
				'paging':false,
				'searching':false,
				'lengthChange':false,
				'info':false,
				'order':[],
				columns: [
					{ title: 'Nation' },
					{ title: "WR's" },
				],
				data: nation_array,
				'columnDefs':[
					{'target':"_all",'searchable':false,'orderable':false,'className':'text-center align-middle'},
				]
			});
			
			var record_array =  Table[Object.keys(Table)[Object.keys(Table).length - 1]].at(-1);
			var record_array = [record_array];
			
			//Current Record Table
			$('#current-record').DataTable({
				'paging':false,
				'searching':false,
				'lengthChange':false,
				'info':false,
				'order':[],
				columns: [
					{ title: "Date Set" },
					{ title: "Name" },
					{ title: "Nation" },
					{ title: "" },
					{ title: "Time / Video" },
				],
				data: record_array,
				'columnDefs':[
					{'target':"_all",'searchable':false,'orderable':false,'className':'text-center align-middle'},
					{'target':0,'width':'15%'},
					{'target':2,'width':'3%'},
					{'target':3,'width':'3%'},
					{'target':4,'width':'15%'},
				]
			});
		}
